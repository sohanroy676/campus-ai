"""Markdown report for an evaluation: plan rates, summaries, paired comparisons, sensitivity."""

from collections.abc import Sequence
from dataclasses import replace

from smartcampus.eval.metrics import METRICS, RunRecord
from smartcampus.eval.stats import (
    Comparison,
    Summary,
    adjust,
    compare,
    limit_counts,
    metric_summaries,
    plan_rate,
    time_summaries,
)

REFERENCE = "joint"  # the method under test; the others are its comparators
PRIMARY_COMPARATOR = "sequential"  # the pre-specified primary comparison: joint vs sequential
PRIMARY_METRICS = ("cancellations", "people_moved")  # its two tests (C and P)

THREATS = (
    "Instances are synthetic and generated by one seeded generator; results say nothing about "
    "real campuses.",
    "Solver stages that hit their time limit return the best solution found, not a proven "
    "optimum; time tiers differ by size, so times are only comparable within a size. The "
    "limit-hit counts show how often that happened.",
    "Methods are given equal optimisation seconds per size tier after a shared greedy start plan. "
    "Wall time differs: joint costs up to 402 s on large instances against 192 s for greedy, so "
    "its gains are bought with roughly twice the compute. Stages stop at wall-clock limits, so "
    "plans on the largest instances can depend on CPU speed; all runs used one machine, one "
    "worker, one job at a time.",
    "The primary comparison is joint against sequential on the lexicographic order (win / tie / "
    "loss) with paired Wilcoxon tests on C and P, Holm-adjusted over those two. Every other "
    "test is secondary and Holm-adjusted as one family (per section); p-values are descriptive "
    "and differences of zero are dropped by the test.",
    "A method without a plan is a solver limit, not a property of the instance; the sensitivity "
    "view scores it as the cancel-everything plan and counts it as a loss.",
    "Re-solve is given the same complete greedy start-plan hint as joint; the hint only guides "
    "its search and its objective (no P, D, S stages) is what defines it, so a re-solve that "
    "ends no better than the start plan is a search limit, not a different objective.",
    "Contract-net's wall-clock limit (the size tier's total solver seconds) starts after its "
    "initial auction, which equals greedy; on large instances the rounds it completes depend on "
    "CPU speed.",
)


def _fmt(summary: Summary | None) -> str:
    if summary is None:
        return "-"
    return f"{summary.median:g} ({summary.q1:g} to {summary.q3:g})"


def _methods(records: Sequence[RunRecord]) -> list[str]:
    seen = {r.method for r in records}
    ordered = ["greedy", "contract_net", "sequential", "resolve", "joint"]
    return [m for m in ordered if m in seen] + sorted(seen - set(ordered))


def _cell(c: Comparison, name: str) -> str:
    test = next((t for t in c.tests if t.metric == name), None)
    if test is None:
        return "(primary)"
    p = "n/a" if test.p_value is None else f"{test.p_value:.3g}"
    holm = "n/a" if test.p_holm is None else f"{test.p_holm:.3g}"
    rate = test.wins / test.n if test.n else 0.0
    return (
        f"{test.median_difference:g}, wins {rate:.0%}, p={p}, Holm p={holm} "
        f"({test.n_nonzero} differ)"
    )


def _comparison_table(
    title: str, comparisons: Sequence[Comparison], metrics: Sequence[str] = METRICS
) -> list[str]:
    lines = [f"**{title}**", ""]
    header = "| comparison | n | win / tie / loss | " + " | ".join(metrics) + " |"
    lines += [header, "|" + "---|" * (3 + len(metrics))]
    for c in comparisons:
        cells = [_cell(c, name) for name in metrics]
        lines.append(
            f"| {c.a} vs {c.b} | {c.n} | {c.wins} / {c.ties} / {c.losses} | "
            + " | ".join(cells)
            + " |"
        )
    return [*lines, ""]


def _only(c: Comparison, metrics: Sequence[str]) -> Comparison:
    return replace(c, tests=tuple(t for t in c.tests if t.metric in metrics))


def _secondary_part(c: Comparison) -> Comparison:
    """Against the primary comparator, C and P belong to the primary tests, not the family."""
    if c.b != PRIMARY_COMPARATOR:
        return c
    return _only(c, tuple(m for m in METRICS if m not in PRIMARY_METRICS))


def _comparisons(records: Sequence[RunRecord], others: Sequence[str]) -> list[str]:
    """Primary comparison first, then the secondary family, each with Holm-adjusted p-values."""
    lines: list[str] = []
    if PRIMARY_COMPARATOR in others:
        raw = compare(records, REFERENCE, PRIMARY_COMPARATOR)
        primary = [
            _only(c, PRIMARY_METRICS)
            for c in adjust([raw], include=lambda _c, t: t.metric in PRIMARY_METRICS)
        ]
        lines += _comparison_table(
            f"Primary: {REFERENCE} against {PRIMARY_COMPARATOR}, instances both solved "
            "(median paired difference, negative favours " + REFERENCE + "; Holm over C and P)",
            primary,
            PRIMARY_METRICS,
        )
    solved = [_secondary_part(compare(records, REFERENCE, m)) for m in others]
    sensitivity = [_secondary_part(compare(records, REFERENCE, m, impute=True)) for m in others]
    adjusted = adjust([*solved, *sensitivity], include=lambda _c, _t: True)
    lines += _comparison_table(
        "Secondary: the other comparisons, instances both solved "
        "(median paired difference, negative favours " + REFERENCE + "; Holm over the whole "
        "secondary family, this table and the next)",
        adjusted[: len(solved)],
    )
    lines += _comparison_table(
        "Secondary sensitivity: all instances, no-plan scored as cancel-everything and counted "
        "as a loss",
        adjusted[len(solved) :],
    )
    return lines


def format_section(records: Sequence[RunRecord], title: str) -> list[str]:
    methods = _methods(records)
    lines = [f"## {title}", ""]
    rates = plan_rate(records)
    lines += ["**Plan rate**", "", "| method | with a plan | run | rate |", "|---|---|---|---|"]
    for m in methods:
        planned, total = rates[m]
        lines.append(f"| {m} | {planned} | {total} | {planned / total:.1%} |")
    lines += ["", "**Median (IQR) per metric, on each method's own solved instances**", ""]
    lines += ["| method | " + " | ".join(METRICS) + " |", "|" + "---|" * (1 + len(METRICS))]
    for m in methods:
        summaries = metric_summaries(records, m)
        lines.append(f"| {m} | " + " | ".join(_fmt(summaries[name]) for name in METRICS) + " |")
    lines += ["", "**Time limits and start plan (runs)**", ""]
    lines += [
        "| method | stopped at a time limit | final plan no better than the greedy start plan |",
        "|---|---|---|",
    ]
    for m in methods:
        limit, unimproved, total = limit_counts(records, m)
        lines.append(f"| {m} | {limit} of {total} | {unimproved} of {total} |")
    lines += ["", "**Planning time in seconds, median (IQR), solved instances**", ""]
    lines += [
        "| method | stage seconds (tier) | wall time total | start plan | after start plan |",
        "|---|---|---|---|---|",
    ]
    for m in methods:
        t = time_summaries(records, m)
        cells = [
            _fmt(t["stage_seconds"]),
            _fmt(t["seconds"]),
            _fmt(t["start_plan_seconds"]),
            _fmt(t["solve_seconds"]),
        ]
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    others = [m for m in methods if m != REFERENCE]
    if REFERENCE in methods and others:
        lines.append("")
        lines += _comparisons(records, others)
    return lines


def _provenance_lines(records: Sequence[RunRecord]) -> list[str]:
    """Which code, generator version and solver tiers produced the records (when stamped)."""
    commits = sorted({r.commit for r in records if r.commit})
    generators = sorted({r.generator_version for r in records if r.generator_version})
    unstamped = sum(1 for r in records if not r.commit)
    if not commits and not generators:
        return []
    lines = [
        f"Code: {', '.join(c[:12] + ('+dirty' if c.endswith('+dirty') else '') for c in commits)}"
        f"; generator version: {', '.join(generators) or 'n/a'}; "
        f"workers and seed per run are in results.jsonl.",
    ]
    if len(commits) > 1 or unstamped:
        lines.append(
            f"WARNING: records come from {len(commits)} code version(s) and {unstamped} run(s) "
            "carry no commit; do not report these as one evaluation."
        )
    return [*lines, ""]


def format_report(records: Sequence[RunRecord]) -> str:
    lines = [
        "# Evaluation report",
        "",
        f"{len({r.instance for r in records})} instances, "
        f"{len(records)} runs. Lower is better on every metric.",
        "",
        *_provenance_lines(records),
    ]
    lines += format_section(records, "All instances")
    for size in ("small", "medium", "large"):
        subset = [r for r in records if r.size == size]
        if subset:
            lines += format_section(subset, f"Size {size}")
    lines += ["## Threats to validity", "", *[f"- {t}" for t in THREATS], ""]
    return "\n".join(lines)
